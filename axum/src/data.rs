//! Fixed sample listings for the view-only service. Nothing is read from or
//! written to a database.

use crate::models::{Intent, Listing, ListingStatus};

struct Sample {
    id: &'static str,
    intent: Intent,
    category: &'static str,
    product: &'static str,
    status: ListingStatus,
    quantity: Option<&'static str>,
    price: Option<f64>,
    currency: &'static str,
    region: Option<&'static str>,
    grade: Option<&'static str>,
    process: Option<&'static str>,
    description: Option<&'static str>,
    image: Option<&'static str>,
    owner: &'static str,
    verified: bool,
    created_at: &'static str,
    views: u32,
}

fn build(index: usize, s: Sample) -> Listing {
    Listing {
        id: s.id.to_string(),
        reference: format!("LST-{}", 1001 + index),
        intent: s.intent,
        category: s.category.to_string(),
        product: s.product.to_string(),
        status: s.status,
        quantity: s.quantity.map(str::to_string),
        price_amount: s.price,
        price_currency: s.currency.to_string(),
        region: s.region.map(str::to_string),
        grade: s.grade.map(str::to_string),
        process: s.process.map(str::to_string),
        description: s.description.map(str::to_string),
        image_url: s.image.map(str::to_string),
        owner_name: s.owner.to_string(),
        owner_verified: s.verified,
        created_at: s.created_at.to_string(),
        views: s.views,
    }
}

